from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class ChatMessage(BaseModel):
    """Represents a single message in a chat history."""

    role: str = Field(..., description="Role of the message sender: 'user', 'model' / 'assistant', or 'system'")
    content: str = Field(..., description="Text content of the message")


class ChatRequest(BaseModel):
    """Request payload for the agent chat endpoint."""

    message: str = Field(..., description="The user's current input prompt or question")
    history: Optional[List[ChatMessage]] = Field(
        default=None,
        description="Optional list of previous messages in the conversation"
    )
    system_prompt: Optional[str] = Field(
        default=None,
        description="Optional override for the agent's system instructions"
    )


class ToolCallRecord(BaseModel):
    """Record of a tool invoked by the agent during reasoning."""

    tool_name: str = Field(..., description="The name of the tool called")
    arguments: Dict[str, Any] = Field(default_factory=dict, description="Arguments passed to the tool")
    result: Any = Field(..., description="Output returned by the tool execution")


class ChatResponse(BaseModel):
    """Response payload returned by the agent."""

    reply: str = Field(..., description="The final text reply generated by the agent")
    tool_calls: List[ToolCallRecord] = Field(
        default_factory=list,
        description="List of tools invoked and their outputs during reasoning"
    )
    model: str = Field(..., description="The LLM model used")
    execution_time_seconds: float = Field(..., description="Total execution time in seconds")


class ToolInfo(BaseModel):
    """Metadata describing an available tool."""

    name: str = Field(..., description="Function name of the tool")
    description: str = Field(..., description="Description of what the tool does")
    parameters: Dict[str, Any] = Field(default_factory=dict, description="JSON schema of expected parameters")


class ToolsListResponse(BaseModel):
    """Response payload listing all registered tools."""

    total_tools: int = Field(..., description="Total count of available tools")
    tools: List[ToolInfo] = Field(..., description="List of registered tools and schemas")
